// npm run api:types: writes the backend's OpenAPI schema to
// frontend/src/api/openapi.json and turns it into frontend/src/api/schema.d.ts,
// so the frontend's types can't drift from the API (API-9).
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const apiDir = path.join(root, 'frontend', 'src', 'api')
const jsonPath = path.join(apiDir, 'openapi.json')
const typesPath = path.join(apiDir, 'schema.d.ts')

execFileSync('uv', ['run', 'python', '-m', 'accountable.openapi', jsonPath], {
  cwd: root,
  stdio: 'inherit',
})

const schema = JSON.parse(readFileSync(jsonPath, 'utf8'))
const ast = await openapiTS(schema)
const header =
  '// Generated by `npm run api:types` from the backend\'s OpenAPI schema. Do not edit.\n\n'
writeFileSync(typesPath, header + astToString(ast), 'utf8')
console.log(`Wrote ${path.relative(root, jsonPath)} and ${path.relative(root, typesPath)}`)
